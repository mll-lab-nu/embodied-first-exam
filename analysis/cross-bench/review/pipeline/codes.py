"""The label vocabulary of the recap, taken from the cross-bench report's codebook (meta/codebook.json), so review
pages and the report use the same names. Writes prompts/codes.json (code -> Chinese name and meaning, read by the
pipeline and the page) and puts the code tables into prompts/recap.md between the `codes` markers, so the prompt is
one self-contained file. Run it again when the codebook changes. usage: python -m pipeline codes"""
from __future__ import annotations
import json, re
from .paths import XB, PROMPT, CODES, jdump

CLAIM = {"correct-success": ["如实说成功", "说做成了，评分也通过"], "false-success": ["声称成功但失败", "说或暗示做成了，评分没过"],
         "knows-failed": ["如实说失败", "说没做成"], "no-claim": ["没有明确说法", "最终消息没说成没成"],
         "matches-live": ["和现场一致", "说法和 agent 现场看到的一致，但评分程序不同意"]}
CAUSE_GROUP = {"understanding": "理解", "interface": "接口", "perception": "感知", "control": "动作", "planning": "步骤",
               "method": "方法", "verification": "查证", "time": "时间", "metacognition": "自我调节", "deliverable": "交付",
               "external": "外部"}
START, END = "<!-- codes: generated by `python -m pipeline codes`, do not edit by hand -->", "<!-- /codes -->"


def pair(v):
    return {"name": v[0], "def": v[1]} if isinstance(v, list) else {"name": v, "def": ""}


def build() -> dict:
    cb = json.load(open(f"{XB}/meta/codebook.json"))
    p = cb["progress_zh"]
    return {
        "level": {k: pair(v) for k, v in p["level"].items()},
        "end": {k: pair(v) for k, v in p["end"].items()},
        "no_return": {k: pair(v) for k, v in p["no_return"].items()},
        "nr_after": {k: pair(v) for k, v in p["nr_after"].items()},
        "cause_group": CAUSE_GROUP,
        "cause": {c: {**pair(cb["cause_zh"].get(c, [c, ""])), "group": g} for g, cs in cb["cause"].items() for c in cs},
        "decision_group": {g: {"name": v[0], "def": v[1], "kinds": v[2]} for g, v in cb["reason_zh"]["group"].items()},
        "decision_kind": {k: pair(v) for k, v in cb["reason_zh"]["kind"].items()},
        "fix": {k: pair(v) for k, v in cb["fix_zh"].items()},
        "would_pass": cb["would_pass_zh"], "who": cb["who_zh"],
        "claim": {k: pair(v) for k, v in CLAIM.items()},
    }


def table(title: str, d: dict, extra=lambda k, v: "") -> str:
    rows = "\n".join(f"| `{k}` | {v['name']} | {v['def']}{extra(k, v)} |" for k, v in d.items())
    return f"### {title}\n| code | name | meaning |\n|---|---|---|\n{rows}\n"


def tables(c: dict) -> str:
    group_of = lambda k: next(g["name"] for g in c["decision_group"].values() if k in g["kinds"])
    return "\n".join([
        table("progress level (highest level reached)", c["level"]),
        table("end (how the trial ended)", c["end"]),
        table("failure cause (one per failure; the group is in brackets)", c["cause"], lambda k, v: f"（{c['cause_group'][v['group']]}）"),
        table("decision kind (the high-level error behind a failure; the group is in brackets)", c["decision_kind"], lambda k, v: f"（{group_of(k)}）"),
        table("no-return type", c["no_return"]),
        table("after the no-return point", c["nr_after"]),
        table("fix (the one step that most likely would have changed the result)", c["fix"]),
        table("final claim", c["claim"])])


def main(argv=None):
    c = build()
    jdump(c, CODES)
    s = open(PROMPT).read()
    s = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda m: f"{START}\n{tables(c)}{END}", s, flags=re.S)
    open(PROMPT, "w").write(s)
    print(f"{len(c['cause'])} 个原因代码，{len(c['fix'])} 个补救代码 -> {CODES}，代码表已写进 {PROMPT}")
