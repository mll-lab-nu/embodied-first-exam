#!/usr/bin/env python3
"""The task list and the release manifest, generated from the tasks; neither is committed to `main`.

Every task carries its own content digest in `tasks/<benchmark>/<task>/DIGEST` (written last by scripts/task_conventions.py
`normalize`; ci_checks/check-dataset-manifest.sh recomputes it) and its own metadata in `task.toml` (mode, family,
oracle, the agent's cutoff `[agent] timeout_sec`, resources, dynamics, and the settings results are grouped by:
reset budget, slowdown, network; the `validated` marker; and `set`, core or excluded, from docs/core_set.toml). Apart from
docs/core_set.toml (a reporting list of the task dirs the headline statistics count, not the task list), nothing in the repository lists
the tasks: pull requests that change different tasks never touch a shared file (as in Terminal-Bench, whose list is its tasks/
directory). After every merge to `main` the workflow `.github/workflows/task-list.yml` writes the list with `list` and
pushes it to the branch `task-list` (never to `main`); a release attaches the same files (`.github/workflows/release.yml`).

    python3 scripts/dataset_manifest.py write [--out FILE]   # Harbor's dataset file for `harbor publish` (default tasks/dataset.toml, ignored by git)
    python3 scripts/dataset_manifest.py list --out DIR       # DIR/tasks.json, DIR/TASKS.md and DIR/dataset.toml
Standard library only.
"""
from __future__ import annotations

import json
import re
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "scripts"))
import task_conventions as tc  # noqa: E402  (benchmark labels, modes)
HEADER = '''# Dataset manifest for robot-coding-bench/robot-coding-bench (generated by scripts/dataset_manifest.py; not committed)
# Publish using: harbor publish

[dataset]
name = "robot-coding-bench/robot-coding-bench"
version = "0.1.0"
description = "Coding agents controlling simulated robots via Python primitives; one replayable trajectory per frozen scene instance, in privileged and standard mode (robosuite, RoboTwin 2.0, DexToolBench, MuJoCo Playground, KinDER, HumanoidBench, MetaWorld+, RoboWits, RoboPaint, RoboLab, BEHAVIOR-1K, VLABench, RoboCasa, RoboCasa365, RoboCasa-GR1)."
authors = []
keywords = [ "robotics", "manipulation", "humanoid", "code-as-policy", "harbor",]
'''
DIGEST = re.compile(r"sha256:[0-9a-f]{64}")


def render() -> str:
    out = [HEADER]
    bad = []
    for t in tc.iter_tasks():
        f = t / "DIGEST"
        d = f.read_text().strip() if f.is_file() else ""
        if not DIGEST.fullmatch(d):
            bad.append(t.name)
            continue
        out.append(f'[[tasks]]\nname = "robot-coding-bench/{t.name}"\ndigest = "{d}"\n')
    if bad:
        raise SystemExit(f"no valid DIGEST in {len(bad)} task(s), e.g. {bad[0]} (python3 scripts/task_conventions.py tasks/<benchmark>/<task>)")
    return "\n".join(out)


def all_tasks() -> list[Path]:
    return tc.iter_tasks()


def entry(t: Path) -> dict:
    """One task's row of the list: what its own files say."""
    d = tomllib.loads((t / "task.toml").read_text())
    md, ag = d.get("metadata", {}), d.get("agent", {})
    r = md.get("resources") or {}
    f = t / "DIGEST"
    return {"name": t.name, "benchmark": tc.bench_of(t), "mode": tc.mode_of(t), "base": tc.base_of(t),
            "family": str(md.get("family", "")), "oracle": md.get("oracle", ""), "timeout_sec": tc.cutoff_for(t),
            "dynamics": md.get("dynamics", ""), "protocol": md.get("protocol", ""), "simulator": md.get("simulator", ""),
            "robot": md.get("robot", ""),
            # the settings results are grouped by (PROTOCOL v2.0 §2, docs/protocol/running.md "Results"): rankings compare only tasks
            # and results of one configuration; `validated` is a marker, ranked together
            "reset_budget": tc.reset_budget_of(t), "slowdown": tc.slowdown_of(t), "network": tc.network_of(t),
            "validated": tc.validated_of(t), "set": tc.set_of(t), "protocol_version": tc.PROTOCOL_VERSION,
            "resources": {k: r[k] for k in ("min_cpus", "min_memory_gb", "min_gpu_memory_gb", "gpu_class") if k in r},
            "digest": f.read_text().strip() if f.is_file() else ""}


def _sec(v) -> str:
    return "—" if v is None else f"{v} s"


def render_md(rows: list[dict], commit: str) -> str:
    modes = list(tc.MODES)
    short = {m: tc.MODE_REGISTRY[m]["short"] for m in modes}
    by_bench: dict[str, list[dict]] = defaultdict(list)
    for r in rows:
        by_bench[r["benchmark"] or "(no benchmark label)"].append(r)
    out = ["# Task list", "",
           f"Generated from `main` at `{commit}` by `scripts/dataset_manifest.py list` (`.github/workflows/task-list.yml`); "
           "do not edit: every number is the task's own (`task.toml`), the core set's from `docs/core_set.toml`. "
           f"{len(rows)} task directories. Modes: " + ", ".join(f"{short[m]} = {m}" for m in modes) + ".", "",
           "## Per benchmark", "",
           "| Benchmark | Tasks (" + " / ".join(short[m] for m in modes) + ") | Cutoff (" + " / ".join(short[m] for m in modes)
           + ") | Oracle (full / partial / none) | Validated | Core set (tasks) | Network (allowlist / open) |", "|---|---|---|---|---|---|---|"]
    for bench in sorted(by_bench, key=str.lower):
        rs = by_bench[bench]
        n = Counter(r["mode"] for r in rs)
        cut = []
        for m in modes:
            vals = sorted({r["timeout_sec"] for r in rs if r["mode"] == m}, key=lambda v: (v is None, v or 0))
            cut.append("—" if not vals else " / ".join(_sec(v) for v in vals) + (" (mixed)" if len(vals) > 1 else ""))
        o = Counter(r["oracle"] or "none" for r in rs)
        net = Counter(r["network"] for r in rs)
        out.append(f"| {bench} | " + " / ".join(str(n[m]) if n[m] else "—" for m in modes) + " | " + " · ".join(cut)
                   + f" | {o['full']} / {o['partial']} / {o['none']} | {sum(bool(r['validated']) for r in rs)} of {len(rs)}"
                   + f" | {sum(r['set'] == 'core' for r in rs) or '—'} | {net['allowlist']} / {net['open']} |")
    out += ["", "## Comparable configurations", "",
            "Results are ranked only within one configuration: protocol version, mode, cutoff, reset budget, slowdown S and "
            "network (`scripts/task_conventions.py` `config_key`; docs/protocol/running.md \"Results\"). Validated and unvalidated tasks "
            "(no `oracle = \"full\"` and no `[metadata] validated = true`) are ranked together; the columns below count "
            "them for reference. Each task's settings are in `tasks.json`.", "",
            "| Mode | Cutoff | Resets | S | Network | Validated tasks | Unvalidated tasks |", "|---|---|---|---|---|---|---|"]
    conf: dict[tuple, list[dict]] = defaultdict(list)
    for r in rows:
        conf[(r["mode"], r["timeout_sec"], r["reset_budget"], r["slowdown"], r["network"])].append(r)
    for (m, c, rb, S, net), rs in sorted(conf.items(), key=lambda kv: (modes.index(kv[0][0]) if kv[0][0] in modes else 99, kv[0][1] or 0,
                                                                 -1 if kv[0][2] is None else kv[0][2], kv[0][3] or 0, kv[0][4])):
        v = sum(bool(r["validated"]) for r in rs)
        out.append(f"| {m} | {_sec(c)} | {'—' if rb is None else rb} | {'—' if S is None else f'{S:g}'} | {net} | {v} | {len(rs) - v} |")
    out += ["", "## Tasks", ""]
    for bench in sorted(by_bench, key=str.lower):
        out += [f"### {bench}", "", "| Task | Mode | Family | Cutoff | Oracle | Validated | Set | Network | Dynamics |",
                "|---|---|---|---|---|---|---|---|---|"]
        out += [f"| `{r['name']}` | {r['mode']} | {r['family'] or '—'} | {_sec(r['timeout_sec'])} | {r['oracle'] or '—'} | "
                f"{'yes' if r['validated'] else 'no'} | {r['set']} | {r['network']} | {r['dynamics'] or '—'} |"
                for r in sorted(by_bench[bench], key=lambda r: r["name"])]
        out.append("")
    return "\n".join(out)


def head_commit() -> str:
    try:
        return subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], check=True, capture_output=True,
                              text=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"


def main(argv: list[str]) -> int:
    if not argv or argv[0] not in ("write", "list"):
        raise SystemExit(__doc__)
    if argv[0] == "list":
        if "--out" not in argv:
            raise SystemExit("list needs --out DIR")
        out = Path(argv[argv.index("--out") + 1])
        out.mkdir(parents=True, exist_ok=True)
        rows, commit = [entry(t) for t in all_tasks()], head_commit()
        (out / "tasks.json").write_text(json.dumps({"commit": commit, "tasks": rows}, indent=1) + "\n", encoding="utf-8")
        (out / "TASKS.md").write_text(render_md(rows, commit), encoding="utf-8")
        (out / "dataset.toml").write_text(render(), encoding="utf-8")
        print(f"wrote {out}/tasks.json, TASKS.md, dataset.toml ({len(rows)} tasks)")
        return 0
    out = Path(argv[argv.index("--out") + 1]) if "--out" in argv else ROOT / "tasks" / "dataset.toml"
    text = render()
    out.write_text(text, encoding="utf-8")
    print(f"wrote {out} ({text.count('[[tasks]]')} tasks)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
