# --------------------------------------------------------------------------------------------------- small helpers
def now():
    return time.time()


def rl(p):
    try:
        return os.readlink(p)
    except OSError:
        return None


def read(p):
    try:
        with open(p) as f:
            return f.read()
    except OSError:
        return None


def stat_id(p):
    try:
        st = os.stat(p)
        return (st.st_dev, st.st_ino)
    except OSError:
        return None


def stat_of(base):
    """(starttime, utime+stime) of the process or thread at /proc path `base`, or None."""
    s = read(base + "/stat")
    if not s:
        return None
    try:
        f = s.rsplit(")", 1)[1].split()
        return int(f[19]), int(f[11]) + int(f[12])
    except (IndexError, ValueError):
        return None


def proc_stat(pid):
    return stat_of(f"{PROC}/{pid}")


def status(pid):
    s = read(f"{PROC}/{pid}/status")
    if not s:
        return {}
    d = {}
    for line in s.splitlines():
        k, _, v = line.partition(":")
        d[k] = v.strip()
    return d


def kb(v):
    try:
        return int((v or "0").split()[0])
    except (ValueError, IndexError):
        return 0


def append(name, obj):
    with open(os.path.join(REC, name), "a") as f:
        f.write(json.dumps(obj, separators=(",", ":")) + "\n")


def write_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(obj, f, indent=1)
    os.replace(tmp, path)


def event(kind, **kw):
    kw.update(t=round(now(), 2), event=kind)
    append("events.jsonl", kw)


def clock(t, start, timeout):
    """The agent's clock for usage.json (robot_coding_bench #231): seconds since `start` (the trial environment's start)
    and, with the task's time limit, the time left and the deadline. Counted from before the agent's session starts, so
    `time_left_s` is never more than the agent really has."""
    out = {"elapsed_s": round(max(0.0, t - start), 1)}
    if timeout:
        out.update(time_limit_s=int(timeout), time_left_s=round(max(0.0, start + timeout - t), 1),
                   deadline_utc=time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(start + timeout)))
    return out


def usage_limits(lim):
    return {k: lim.get(k) for k in ("max_gpu_memory_gb", "max_memory_gb", "max_processes", "max_disk_gb", "sustain_sec",
                                    "window_sec")}


def open_in_root(root, rel):
    """A read-only fd of the regular file `rel` under the directory `root` (a container's /proc/<pid>/root), never
    through a symbolic link (an absolute link would resolve in the monitor's own file system), or None."""
    fd = None
    try:
        fd = os.open(root, os.O_RDONLY | os.O_DIRECTORY)
        parts = rel.split("/")
        for part in parts[:-1]:
            nfd = os.open(part, os.O_RDONLY | os.O_DIRECTORY | os.O_NOFOLLOW, dir_fd=fd)
            os.close(fd)
            fd = nfd
        f = os.open(parts[-1], os.O_RDONLY | os.O_NOFOLLOW | os.O_NONBLOCK, dir_fd=fd)
        if not stat_mod.S_ISREG(os.fstat(f).st_mode):
            os.close(f)
            return None
        return f
    except OSError:
        return None
    finally:
        if fd is not None:
            os.close(fd)


class SessionLogCopy:
    """Append-only copy of the agent's session log into the record (#233). State (inode, offset, segment, tail hash)
    lives in the record's state.json, so a restarted monitor goes on where it was."""

    def __init__(self, state=None):
        self.s = dict(state or {"ino": None, "off": 0, "seg": 0, "tail": "", "copied": 0, "gone": False})

    def step(self, root):
        import hashlib
        fd = open_in_root(root, SESSION_LOG)
        if fd is None:
            if self.s["ino"] is not None and not self.s["gone"]:
                self.s["gone"] = True
                event("session_log_removed", copied=self.s["copied"], segment=self.s["seg"])
            return
        try:
            st = os.fstat(fd)
            s = self.s

            def tail_of(end):
                os.lseek(fd, max(0, end - SESSION_LOG_TAIL), 0)
                return hashlib.sha256(os.read(fd, min(SESSION_LOG_TAIL, end))).hexdigest()

            if s["ino"] is not None and (st.st_ino != s["ino"] or st.st_size < s["off"] or s["gone"]
                                         or (s["off"] and tail_of(s["off"]) != s["tail"])):
                event("session_log_rewritten", copied=s["off"], size=st.st_size, segment=s["seg"] + 1,
                      why="replaced" if st.st_ino != s["ino"] else "truncated" if st.st_size < s["off"] else
                      "back after removal" if s["gone"] else "rewritten")
                s.update(off=0, seg=s["seg"] + 1, tail="")
            s.update(ino=st.st_ino, gone=False)
            n = min(st.st_size - s["off"], SESSION_LOG_MAX - s["copied"])
            if n <= 0:
                return
            os.lseek(fd, s["off"], 0)
            data = b""
            while len(data) < n:
                chunk = os.read(fd, n - len(data))
                if not chunk:
                    break
                data += chunk
            d = os.path.join(REC, "session_log")
            os.makedirs(d, exist_ok=True)
            with open(os.path.join(d, "%d.jsonl" % s["seg"]), "ab") as out:
                out.write(data)
            s["off"] += len(data)
            s["copied"] += len(data)
            s["tail"] = tail_of(s["off"])
        finally:
            os.close(fd)


def no_dump():
    """Not dumpable: without CAP_SYS_PTRACE nobody (not even the same uid) can open /proc/<monitor>/{root,mem,fd}."""
    try:
        ctypes.CDLL(None, use_errno=True).prctl(4, 0, 0, 0, 0)    # PR_SET_DUMPABLE = 4
    except Exception:
        pass


# --------------------------------------------------------------------------------------------------- NVML
class Nvml:
    """Per-process GPU memory (host PIDs: the monitor runs in the host PID namespace) and per-card use, via libnvidia-ml
    (ctypes; no nvidia-smi child processes)."""

    class Proc(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong),
                    ("gpuInstanceId", ctypes.c_uint), ("computeInstanceId", ctypes.c_uint)]

    class Proc1(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong)]

    class Mem(ctypes.Structure):
        _fields_ = [("total", ctypes.c_ulonglong), ("free", ctypes.c_ulonglong), ("used", ctypes.c_ulonglong)]

    def __init__(self):
        self.lib = ctypes.CDLL("libnvidia-ml.so.1")
        if self.lib.nvmlInit_v2() != 0:
            raise RuntimeError("nvmlInit failed")
        n = ctypes.c_uint(0)
        self.lib.nvmlDeviceGetCount_v2(ctypes.byref(n))
        self.handles = []
        for i in range(n.value):
            h = ctypes.c_void_p()
            if self.lib.nvmlDeviceGetHandleByIndex_v2(i, ctypes.byref(h)) == 0:
                self.handles.append(h)
        self.fns = []
        for name, st in (("nvmlDeviceGetComputeRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses", self.Proc1),
                         ("nvmlDeviceGetGraphicsRunningProcesses", self.Proc1)):
            kind = "compute" if "Compute" in name else "graphics"
            if any(k == kind for k, _, _ in self.fns):
                continue
            try:
                self.fns.append((kind, getattr(self.lib, name), st))
            except AttributeError:
                pass

    def sample(self):
        """({host pid: MiB}, {card index: (used MiB, total MiB)}, {host pids whose memory NVML does not tell})."""
        per, cards, unknown = {}, {}, set()
        for i, h in enumerate(self.handles):
            m = self.Mem()
            if self.lib.nvmlDeviceGetMemoryInfo(h, ctypes.byref(m)) == 0:
                cards[i] = (m.used // 2 ** 20, m.total // 2 ** 20)
            seen = {}
            for _kind, fn, st in self.fns:
                cnt = ctypes.c_uint(0)
                rc = fn(h, ctypes.byref(cnt), None)
                if rc not in (0, 7):                 # 7 = NVML_ERROR_INSUFFICIENT_SIZE: cnt now holds the count
                    continue
                cnt = ctypes.c_uint(cnt.value + 16)
                arr = (st * cnt.value)()
                if fn(h, ctypes.byref(cnt), arr) != 0:
                    continue
                for k in range(cnt.value):
                    mem = arr[k].usedGpuMemory
                    if mem >= 2 ** 63:               # NVML_VALUE_NOT_AVAILABLE (MIG / vGPU / WSL): not a zero
                        unknown.add(arr[k].pid)
                        mib = 0
                    else:
                        mib = mem // 2 ** 20
                    seen[arr[k].pid] = max(seen.get(arr[k].pid, 0), mib)   # a C+G process is in both lists
            for p, v in seen.items():
                per[p] = per.get(p, 0) + v
        return per, cards, unknown


# --------------------------------------------------------------------------------------------------- disk
class DiskWalk:
    """One measurement of the files under `paths` below `root` (the agent container's root, seen through /proc): the
    sum of st_blocks, every hard-linked file once, never descending into another mount (a directory on another device;
    files are not asked for theirs: on an overlay root whose layers sit on different file systems they report their
    layer's), `exclude` skipped. It runs in
    slices (step) between the monitor's samples, so a large tree delays no sample. `done` only when every directory was
    read: only then is `bytes` a measurement; before that it is a lower bound."""

    def __init__(self, root, paths, exclude):
        self.root, self.t0 = root, now()
        self.bytes = self.entries = 0
        self.done, self.why = False, None
        self._it = self._walk(list(paths), {root + x.rstrip("/") for x in exclude})

    def _walk(self, paths, excl):
        linked = set()                               # (dev, ino) of files with several names: counted once
        for base in paths:
            top = self.root + base
            try:
                dev = os.lstat(top).st_dev
            except FileNotFoundError:
                continue                             # the path does not exist in this container: nothing under it
            except OSError as e:
                self.why = f"{base}: {type(e).__name__}"
                return
            stack = [top]
            while stack:
                d = stack.pop()
                try:
                    it = os.scandir(d)
                except FileNotFoundError:
                    continue                         # removed since its parent was read
                except OSError as e:
                    self.why = f"{d[len(self.root):]}: {type(e).__name__}"
                    return
                with it:
                    for e in it:
                        try:
                            st = e.stat(follow_symlinks=False)
                        except OSError:
                            continue                 # removed meanwhile
                        if stat_mod.S_ISDIR(st.st_mode):
                            if st.st_dev != dev or e.path in excl:
                                continue             # another mount (never crossed: not the container's own files)
                            stack.append(e.path)
                        elif st.st_nlink > 1:
                            k = (st.st_dev, st.st_ino)
                            if k in linked:
                                continue
                            linked.add(k)
                        self.bytes += st.st_blocks * 512
                        self.entries += 1
                        if self.entries % 256 == 0:
                            yield
                yield
        self.done = True

    def step(self, budget_sec):
        """Walk on for at most `budget_sec`; True when the walk has ended (done, or failed with `why`)."""
        end = now() + budget_sec
        for _ in self._it:
            if now() >= end:
                return False
        return True


# --------------------------------------------------------------------------------------------------- OOM kills
class OomWatch:
    """Kernel OOM kills of the watched containers, from each one's cgroup v2 `memory.events`:
      oom       times the cgroup's memory reached its own limit (memory.max) and an allocation was about to fail
      oom_kill  processes of the cgroup killed by any OOM killer (its own limit's, an enclosing cgroup's, the host's)
    A kill whose `oom` counter rose with it (or within OOM_CAP_WINDOW_SEC before) happened at the container's own cap
    (`cause: "cap"`); one without is the host's or an enclosing cgroup's OOM killer (`cause: "host"`), which the
    container did not cause by its own use (PROTOCOL §2.10: nothing another trial does can fail a trial).

    The counters live and die with the cgroup, and a container whose main process is killed is gone (and restarted by
    compose with fresh counters) within milliseconds. So the files are read by this object's own thread, every
    OOM_COLD_SEC, at once when the kernel signals a change (poll: memory.events notifies), and every OOM_HOT_SEC for a
    while after any change (the `max` counter rises under memory pressure, before a kill). A kill that removes the
    cgroup within about a millisecond can still be missed: such a kill is then in no record.

    scan() reads every file once; the sampler calls it at each tick when the thread does not run (the tests). The
    thread ends when the record is sealed."""

    def __init__(self):
        self.lock = threading.Lock()
        self.w = {}                  # cgroup dir -> {"role", "scope", "fd", "kill", "oom", "sig", "cap_t", "seen"}
        self.hot_until = 0.0
        self.thread = None
        self.stopped = False         # set at the seal: the record is closed, like the samples

    def watch(self, cg, role, scope, t):
        """The sampler saw this container's cgroup at time t."""
        with self.lock:
            e = self.w.get(cg)
            if e is None:
                e = self.w[cg] = {"fd": None, "kill": None, "oom": None, "sig": None, "cap_t": None}
            e.update(role=role, scope=bool(scope), seen=t)

    @staticmethod
    def _close(e):
        if e["fd"] is not None:
            try:
                os.close(e["fd"])
            except OSError:
                pass
            e["fd"] = None

    def _read(self, cg, e):
        """The counters of the cgroup's memory.events ({} when the file cannot be read: the container is not up).
        A file that stops answering belonged to a cgroup that is gone; the same path opened again is a new cgroup (the
        container restarted: another directory, by its inode and creation time), whose counters all belong to the
        trial: they are compared with 0. The same cgroup opened again keeps what was already counted."""
        for _ in (0, 1):
            try:
                if e["fd"] is None:
                    e["fd"] = os.open(cg + "/memory.events", os.O_RDONLY)
                    st = os.stat(cg)
                    ident = (st.st_dev, st.st_ino, st.st_ctime_ns)
                    if e["sig"] is not None and ident != e.get("ident"):
                        e["kill"] = e["oom"] = 0     # read before, gone, here again: another instance of the cgroup
                    e["ident"] = ident
                os.lseek(e["fd"], 0, os.SEEK_SET)
                out = {}
                for line in os.read(e["fd"], 8192).decode("ascii", "replace").splitlines():
                    k, _, v = line.partition(" ")
                    if v.strip().isdigit():
                        out[k] = int(v)
                return out
            except OSError:
                self._close(e)
        return {}

    def scan(self):
        """Read every watched file once and record the kills since the last reading. True when a counter changed."""
        changed = False
        with self.lock:
            t = now()
            for cg, e in list(self.w.items()):
                if t - e["seen"] > OOM_FORGET_SEC:
                    self._close(e)
                    del self.w[cg]
                    continue
                c = self._read(cg, e)
                if "oom_kill" not in c:
                    continue
                kill, oom = c["oom_kill"], c.get("oom", 0)
                sig = (kill, oom, c.get("max", 0))
                if e["kill"] is None or kill < e["kill"] or oom < e["oom"]:
                    # the first reading is the baseline; counters that went back are a new cgroup under the same path
                    e["kill"], e["oom"] = (kill, oom) if e["kill"] is None else (0, 0)
                changed |= sig != e["sig"]
                if oom > e["oom"]:
                    e["cap_t"] = t
                if kill > e["kill"]:
                    at_cap = e["cap_t"] is not None and t - e["cap_t"] <= OOM_CAP_WINDOW_SEC
                    kw = {"role": e["role"], "scope": e["scope"], "count": kill - e["kill"],
                          "cause": "cap" if at_cap else "host", "cap_hits": oom - e["oom"]}
                    for name, key in (("memory.max", "memory_cap_gb"), ("memory.current", "memory_current_gb")):
                        v = (read(cg + "/" + name) or "").strip()      # evidence only: the cause is the counters'
                        if v.isdigit():
                            kw[key] = round(int(v) / GIB, 3)
                    event("oom", **kw)
                e["kill"], e["oom"], e["sig"] = kill, oom, sig
        return changed

    def start(self):
        self.thread = threading.Thread(target=self._loop, name="rcb-oom-watch", daemon=True)
        self.thread.start()

    def _loop(self):
        said = False
        while not self.stopped:
            try:
                if self.scan():
                    self.hot_until = now() + OOM_HOT_FOR_SEC
                if now() < self.hot_until:
                    time.sleep(OOM_HOT_SEC)
                    continue
                with self.lock:
                    fds = [e["fd"] for e in self.w.values() if e["fd"] is not None]
                if not fds:
                    time.sleep(OOM_COLD_SEC)
                    continue
                p = select.poll()                     # memory.events notifies its readers (POLLPRI) when it changes
                for fd in fds:
                    p.register(fd, select.POLLPRI | select.POLLERR)
                if p.poll(OOM_COLD_SEC * 1000):
                    self.hot_until = now() + OOM_HOT_FOR_SEC
            except Exception as e:                    # never stop watching
                if not said:
                    said = True
                    try:
                        event("error", why=f"oom watch: {type(e).__name__}: {e}"[:300])
                    except Exception:
                        pass
                time.sleep(OOM_COLD_SEC)


