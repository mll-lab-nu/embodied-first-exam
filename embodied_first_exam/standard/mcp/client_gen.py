#!/usr/bin/env python3
"""Generates the Python client of the efe-robot tools (mode standard-mcp-shell): `/opt/tools/efe_robot.py`, one function
per tool, from the same tool definitions the MCP server lists for this robot (schema/tools.v0.json narrowed by the
task's manifest, schema.tools_for). Same names, same arguments, same results: a function call is the tool call, sent
to the same server (python3 /opt/tools/efe_mcp/server.py, its own process) over stdio.

    python3 client_gen.py <manifest.json> <out.py>

Standard library only (the generated file too, besides the server's own numpy / Pillow)."""
from __future__ import annotations
import json, keyword, pathlib, sys, textwrap

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import schema as sch  # noqa: E402

HEADER = '''"""efe_robot: the efe-robot tools as Python functions (mode standard-mcp-shell; generated by
embodied_first_exam/standard/mcp/client_gen.py for this robot -- do not edit).

Each function sends the tool call of the same name, with the same arguments, to the efe-robot MCP server (the server
your MCP tools use: python3 /opt/tools/efe_mcp/server.py, started here as its own process on first use) and returns
the tool's JSON result as a dict. A call still running when its result is due ({"pending": true, "operation": id}) is
waited for here, so every function returns the final result. A tool error raises ToolError (its .payload is the
error JSON). Images are files under /app/obs/ (the result gives their paths); `inline_cameras` has no effect here.

    import efe_robot as R                      # /opt/tools is on PYTHONPATH
    R.describe_robot()
    R.observe(cameras=["head"], depth=True)
    R.move_robot(goals=[{"target": "left", "gripper": 1.0}])

Command line: python3 /opt/tools/efe_robot.py <tool> ['<JSON arguments>']   (prints the result)
"""
from __future__ import annotations
import importlib.util, json, os, pathlib, sys

SERVER = os.environ.get("EFE_MCP_SERVER", "/opt/tools/efe_mcp/server.py")
TOOLS = json.loads(%(tools)r)
_client = None


class ToolError(RuntimeError):
    def __init__(self, payload):
        super().__init__(payload.get("error") if isinstance(payload, dict) else str(payload))
        self.payload = payload


def _mcp():
    global _client
    if _client is None:
        spec = importlib.util.spec_from_file_location("efe_mcp_client", pathlib.Path(SERVER).parent / "mcp_client.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        env = {"EFE_MCP_VIA": "python", "EFE_MCP_FILE_TAG": "py"}
        _client = (mod, mod.McpClient(cmd=[sys.executable, SERVER], env=env))
    return _client


def call(tool: str, **arguments) -> dict:
    """The tool `tool` with these arguments (None values left out); the final result as a dict."""
    if tool not in TOOLS:
        raise ValueError(f"no tool {tool!r}; tools: {', '.join(TOOLS)}")
    mod, c = _mcp()
    args = {k: v for k, v in arguments.items() if v is not None}
    try:
        return c.call(tool, **args)
    except mod.McpToolError as e:
        raise ToolError(e.payload) from None


def close():
    global _client
    if _client is not None:
        _client[1].close()
        _client = None

'''

FOOTER = '''

def _main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        print("tools:", ", ".join(TOOLS))
        return 0
    args = json.loads(argv[1]) if len(argv) > 1 else {}
    try:
        out = call(argv[0], **args)
    except ToolError as e:
        print(json.dumps(e.payload, indent=1))
        return 1
    finally:
        close()
    print(json.dumps(out, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(_main(sys.argv[1:]))
'''


def type_text(p: dict) -> str:
    if "enum" in p:
        return " | ".join(json.dumps(x) for x in p["enum"])
    t = p.get("type")
    if t == "array":
        it = p.get("items") or {}
        return f"list[{type_text(it) if it else 'any'}]"
    if t == "object":
        props = p.get("properties") or {}
        return "{" + ", ".join(props) + "}" if props else "dict"
    return {"number": "float", "integer": "int", "string": "str", "boolean": "bool"}.get(t, t or "any")


def doc_of(tool: dict) -> str:
    s = tool["inputSchema"]
    props, req = s.get("properties") or {}, set(s.get("required") or [])
    lines = textwrap.wrap(tool.get("description", ""), 112) or [tool["name"]]
    if props:
        lines += ["", "Arguments:"]
        for k, p in props.items():
            head = f"  {k} ({type_text(p)}{', required' if k in req else ''}): "
            body = p.get("description", "")
            rng = [f"{w} {p[w]}" for w in ("minimum", "maximum", "minItems", "maxItems") if w in p]
            if rng:
                body += f" [{', '.join(rng)}]"
            w = textwrap.wrap(head + body, 112, subsequent_indent="      ")
            lines += w
            sub = (p.get("items") or {}).get("properties") if p.get("type") == "array" else p.get("properties")
            for kk, pp in (sub or {}).items():
                lines += textwrap.wrap(f"    - {kk} ({type_text(pp)}): {pp.get('description', '')}", 112,
                                       subsequent_indent="        ")
    return "\n".join(lines)


def function_of(tool: dict) -> str:
    s = tool["inputSchema"]
    props, req = s.get("properties") or {}, list(s.get("required") or [])
    names = [k for k in props if k.isidentifier() and not keyword.iskeyword(k)]
    req_names = [k for k in req if k in names]
    opt = [k for k in names if k not in req]
    sig = req_names + (["*"] + [f"{k}=None" for k in opt] if opt else [])
    body = ", ".join(f"{k}={k}" for k in names)
    doc = textwrap.indent(doc_of(tool), "    ").strip("\n")
    return (f"def {tool['name']}({', '.join(sig)}) -> dict:\n"
            f'    """{doc.lstrip()}\n    """\n'
            f"    return call({tool['name']!r}{', ' + body if body else ''})\n")


def generate(m: dict) -> str:
    tools = sch.tools_for(m)
    slim = {t["name"]: {"description": t.get("description", "")[:200]} for t in tools}
    out = HEADER % {"tools": json.dumps(slim)}
    out += "\n\n".join(function_of(t) for t in tools)
    out += FOOTER
    compile(out, "efe_robot.py", "exec")
    return out


def main(argv):
    if len(argv) != 2:
        raise SystemExit(__doc__)
    m = json.loads(pathlib.Path(argv[0]).read_text())
    pathlib.Path(argv[1]).write_text(generate(m))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
