#!/usr/bin/env python3
"""rcb_monitor: the trusted resource-limits monitor sidecar of every task (docs/protocol/README.md §2.10, record rcb-monitor/1).

Runs as the compose service `rcb_monitor` (generated by scripts/rcb_monitor/inject.py): `pid: host`, `cgroup: host`,
`network_mode: none`, CAP_SYS_PTRACE, the task's GPU reservation, its code read-only from the task directory. The agent
cannot see it (another PID namespace), reach it (no network) or write its record (its own file system).

Which containers it watches: the services that mount the trial's beacon volume `rcb_limits` (read-only at
/run/rcb-limits) are in scope, the ones that mount `rcb_observe` are only recorded (the benchmark's own services: the
simulator sidecar of standard modes, RoboPaint's privileged `scorer`). The compose project names both volumes, so they are unique to the trial; the monitor finds the containers as
the mount namespaces whose /run/rcb-limits is the same directory as its own (docker compose exec'd processes included).
A namespace that does not show the beacon is asked again at every tick (a container that is still being set up has the
host's root until its pivot_root: "no" is never remembered); a "yes" is kept only while the process that proved it lives.
A process whose first thread has exited is found through a thread that lives; a zombie counts in its parent's container.

Every tick (5 s; disk every 60 s) it samples, per container and summed over the scope: GPU memory (NVML, per process,
compute and graphics), memory (cgroup anon+shmem when the container has its own cgroup, else PSS anon+shmem), processes
(TGIDs, zombies included), disk growth under the limits' disk_paths in the agent's container (complete walks only, in
slices between the samples), CPU (recorded only). It appends to /var/rcb-monitor/samples.jsonl and
events.jsonl and writes the agent-visible /run/rcb-limits/usage.json: the current values, the limits and the agent's
clock (`elapsed_s`, `time_left_s`, `deadline_utc`: the task's `[agent] timeout_sec`, counted from the monitor's start,
which is the trial environment's start, a little before the agent's session starts, so it never overstates the time left).

The agent-side session log (robot_coding_bench #233): the privileged tooling writes /app/output/rcb_session_log.jsonl
from the agent's own process, so the agent can delete or rewrite it. Every tick the monitor copies what was appended to
it, append-only, into its record (session_log/<segment>.jsonl; a truncated, replaced or rewritten file starts a new
segment, a removed one keeps its copy; `session_log_rewritten` / `session_log_removed` events). The verifier step
(rcb_limits.sanitize, before the grader) gives the grader that copy when the agent's file is not what was written.

Kernel OOM kills (`oom` events) are read from each watched container's cgroup `memory.events` by a thread of its own
(OomWatch), many times a second: a kill that takes the container's main process with it ends the container, and compose
restarts it with a new cgroup whose counters start at 0, within milliseconds -- a reading once per tick never sees it.
Every event says whom it hit (`scope`: a container the limits bind, or a benchmark-owned service that is only
recorded) and why (`cause`): "cap" when the container's own `oom` counter rose with it (the kernel says its memory
reached its own cap), else "host" (the host's OOM killer, or an enclosing cgroup's: not this container's doing).
Only a "cap" kill in the scope is a violation (rcb_limits.violations); the verifier step reports the others.

RCB_LIMITS_ENFORCE=1 (run-time switch; compose default 0; 0/1/true/false, anything else is a fatal record): once a
violation is confirmed (rcb_limits.violations, the verifier's own rule) the monitor SIGKILLs every in-scope process
except each container's PID 1, so the agent stops at once and Harbor goes on to collection and the verifier (an agent
killed this way ends like one that exited non-zero). It also protects the host (`emergency_kill` events, never a
violation by themselves): above EMERGENCY_GPU_FACTOR x the GPU-memory limit at one sample it kills the scope's process
that holds the most GPU memory; where the runtime applies no kernel memory cap, it stands in for it and kills the
largest process once the scope is above its declared memory caps.
0: it only records.

    python3 monitor.py run            # the service's command
    python3 monitor.py seal --wait 90 # the first sidecar collect hook: seal the record (summary.json), print it
    python3 monitor.py beacon         # for a runner whose container runtime cannot run the monitor (no `pid: host`,
                                      # e.g. rootless podman without cgroups): the same service without pid/cgroup host,
                                      # writing only the agent's clock and `"measured": false` to usage.json
"""
