def rig_sampler(rig, m, rest_qpos):
    """Random legal poses of a library robot: the controlled vector u (lift, waist, the hand arm) uniform inside the
    rig's ranges (rig.LO / rig.HI; the base and the walking command at rest), the other arm's joints uniform inside
    their MJCF ranges; a legged robot's legs uniform in their ranges (its pelvis where it stands); the base at rest."""
    import numpy as np
    o = getattr(rig, "o", 0)
    other = rig.qadr[-7:]
    jr = {int(m.jnt_qposadr[j]): m.jnt_range[j] for j in range(m.njnt)}
    lo_o = np.array([jr[int(a)][0] for a in other])
    hi_o = np.array([jr[int(a)][1] for a in other])
    legs = rig.lqadr if not getattr(rig, "fixed_base", True) else []   # a legged robot's legs: uniform too
    lo_l = np.array([jr[int(a)][0] for a in legs])
    hi_l = np.array([jr[int(a)][1] for a in legs])

    def sample(rng):
        u = np.array(rig.rest, float)
        u[3:] = rng.uniform(rig.LO[3:], rig.HI[3:])
        q = rest_qpos.copy()
        t = rig.joint_targets(u)
        q[rig.qadr[o:]] = t[o:]
        q[other] = rng.uniform(lo_o, hi_o)
        if len(legs):
            q[legs] = rng.uniform(lo_l, hi_l)
        return q
    return sample


def check_model(m, tag, rest_qpos, sample, n_random=200, seed=0, structural=0.95, tol=1e-4):
    """The static self-collision check of one compiled model: (problems, report). At rest_qpos no pair of `tag`
    penetrates (more than tol); over n_random random legal poses (sample(rng) -> qpos) no pair penetrates in more
    than `structural` of them (a mount overlap: exclude it with a reason)."""
    import numpy as np
    import mujoco as mj
    d = mj.MjData(m)
    pairs = [i for i in range(m.npair) if is_tag(mj.mj_id2name(m, mj.mjtObj.mjOBJ_PAIR, i), tag)]
    gname = lambda g: mj.mj_id2name(m, mj.mjtObj.mjOBJ_GEOM, int(g))
    dist = lambda i, cut: mj.mj_geomDistance(m, d, int(m.pair_geom1[i]), int(m.pair_geom2[i]), cut, None)
    probs = []
    d.qpos[:] = rest_qpos
    mj.mj_kinematics(m, d)
    rest_pen, closest = [], (None, 1.0)
    for i in pairs:
        x = dist(i, 0.05)
        if x < closest[1]:
            closest = ((gname(m.pair_geom1[i]), gname(m.pair_geom2[i])), x)
        if x < -tol:
            rest_pen.append((gname(m.pair_geom1[i]), gname(m.pair_geom2[i]), round(float(x), 4)))
    for a, b, x in rest_pen:
        probs.append(f"at rest {a} x {b} penetrate by {-x * 100:.2f} cm (fix the rest pose or exclude the pair "
                     "with a reason)")
    rng = np.random.default_rng(seed)
    cnt = np.zeros(len(pairs), int)
    any_hit = 0
    for _ in range(n_random):
        d.qpos[:] = sample(rng)
        mj.mj_kinematics(m, d)
        hit = False
        for k, i in enumerate(pairs):
            if dist(i, 0.01) < -tol:
                cnt[k] += 1
                hit = True
        any_hit += hit
    for k, i in enumerate(pairs):
        if cnt[k] > structural * n_random:
            probs.append(f"{gname(m.pair_geom1[i])} x {gname(m.pair_geom2[i])} penetrate in {cnt[k]} of {n_random} "
                         "random legal poses: a structural overlap (exclude it with a reason)")
    report = {"pairs": len(pairs), "rest_penetrating": rest_pen,
              "rest_closest": [list(closest[0] or ()), round(float(closest[1]), 4)],
              "random_poses": n_random, "random_poses_with_self_contact": int(any_hit),
              "most_frequent": sorted(([gname(m.pair_geom1[i]), gname(m.pair_geom2[i]), int(cnt[k])]
                                       for k, i in enumerate(pairs) if cnt[k]), key=lambda x: -x[2])[:5]}
    return probs, report


def configurations():
    """The hands a library robot is checked with: none, then every hand of bodies/hands/hands.toml on the right
    wrist, with its status (a "ready" hand fails the check, a "draft" hand only warns)."""
    import tomllib
    hands = tomllib.loads((HERE / "hands" / "hands.toml").read_text())
    return [(None, "ready")] + [(h, v.get("status", "draft")) for h, v in hands.items()]


def compiled(B, hand, other_hand=None, **kw):
    """One library robot (prefix A_) alone in an empty world: (model, info)."""
    import mujoco as mj
    root = ET.Element("mujoco", model="selfcol_check")
    ET.SubElement(root, "compiler", angle="radian", autolimits="true")
    ET.SubElement(root, "option", timestep="0.001")
    for sec in ("default", "asset", "worldbody"):
        ET.SubElement(root, sec)
    if other_hand:
        kw["other_hand"] = other_hand
    info = B.mount(root, "A_", (0.0, 0.0, 0.0), 0.0, hand=hand, **kw)
    return mj.MjModel.from_xml_string(ET.tostring(root, encoding="unicode")), info


def check_body(name, n_random=200) -> tuple[list, list, dict]:
    """(failures, warnings, report) of one library robot: its declaration is used (no unused exclusion), and in
    every configuration the model passes check_model at the rest pose and over random legal poses."""
    import mujoco as mj
    sys.path.insert(0, str(HERE.parent))
    from bodies import load_body
    B = load_body(name)
    fails, warns, rep = [], [], {}
    unused = None
    for hand, status in configurations():
        m, info = compiled(B, hand)
        d = mj.MjData(m)
        rig = B.rig(m, "A_", hand=hand)
        rig.place(d, rig.rest)
        q0 = d.qpos.copy()
        probs, r = check_model(m, info["selfcol_tag"], q0, rig_sampler(rig, m, q0), n_random=n_random)
        rep[hand or "none"] = r
        u = set(map(tuple, info["selfcol_unused"]))
        unused = u if unused is None else unused & u          # unused with every hand
        for p in probs:
            (fails if status == "ready" else warns).append(f"{name} hand={hand or 'none'}: {p}")
        if r["pairs"] == 0:
            fails.append(f"{name} hand={hand or 'none'}: no self-collision pair")
    for u in sorted(unused or ()):
        fails.append(f"{name}: exclusion {list(u)} matches no geom pair (remove it)")
    return fails, warns, rep


def main(argv=None):
    import argparse
    import json
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=["check", "pairs", "scene"])
    ap.add_argument("robots", nargs="*")
    ap.add_argument("--random", type=int, default=200)
    ap.add_argument("--json")
    a = ap.parse_args(argv)
    sys.path.insert(0, str(HERE.parent))
    from bodies import BODIES
    if a.cmd == "scene":                      # robots = sport directories: write their scenes' generated blocks
        for sd in a.robots:
            for line in write_sport_scenes(Path(sd)):
                print(line)
        return 0
    robots = a.robots or list(BODIES)
    if a.cmd == "pairs":
        from bodies import load_body
        for r in robots:
            B = load_body(r)
            root = ET.Element("mujoco")
            for sec in ("default", "asset", "worldbody"):
                ET.SubElement(root, sec)
            p = B.mount(root, "", (0.0, 0.0, 0.0), 0.0, hand="paddle")["selfcol_plan"]
            print(f"== {r}: {p.summary()}")
            for x in p.pairs:
                print(f"   pair  {x[4]:13s} {x[2]} / {x[0]}  x  {x[3]} / {x[1]}")
            for x in p.excluded:
                print(f"   excl  {x[0]} x {x[1]}: {x[2]}")
        return 0
    allf, out = [], {}
    for r in robots:
        f, w, rep = check_body(r, a.random)
        out[r] = {"failures": f, "warnings": w, "report": rep}
        for x in w:
            print("WARN [self-collision]", x)
        for x in f:
            print("FAIL [self-collision]", x)
        print(f"self-collision {r}: " + ", ".join(f"{h}: {v['pairs']} pairs, {v['random_poses_with_self_contact']}/"
                                                  f"{v['random_poses']} random poses in contact"
                                                  for h, v in rep.items()) + ("" if f else "; ok"))
        allf += f
    if a.json:
        Path(a.json).write_text(json.dumps(out, indent=1))
    return 1 if allf else 0


if __name__ == "__main__":
    sys.exit(main())
