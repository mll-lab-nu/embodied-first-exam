"""Authoring-only: copy the approved T07 presentation geometry into ``assets/`` (OBJ + PNG + sha256 manifest).

Source (read-only): the approved T07 presentation export ``studio-v2`` (``geometry.npz`` meshes 0-3, the two AA
wrap textures). The AA cell mesh is an original UV-mapped cylinder generated here so the wrap texture can be shown
in MuJoCo previews. Run once; the generated files are committed with ``manifest.json``.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil

import numpy as np

HERE = Path(__file__).resolve().parents[1]
MESHES = {0: "remote_shell", 1: "battery_door", 2: "thumb_pad", 3: "open_arrow"}


def write_obj(path, vertices, faces, uv=None):
    lines = ["# generated by tools/export_assets.py"]
    lines += [f"v {x:.6f} {y:.6f} {z:.6f}" for x, y, z in vertices]
    if uv is not None:
        lines += [f"vt {u:.6f} {v:.6f}" for u, v in uv]
        lines += [f"f {a + 1}/{a + 1} {b + 1}/{b + 1} {c + 1}/{c + 1}" for a, b, c in faces]
    else:
        lines += [f"f {a + 1} {b + 1} {c + 1}" for a, b, c in faces]
    path.write_text("\n".join(lines) + "\n")


def cell_mesh(radius=0.007, half_length=0.0245, segments=48):
    """Open UV-mapped side wall of an AA cell along +z (u around, v along; v=1 at the + end)."""
    vertices, uv, faces = [], [], []
    for j, z in enumerate((-half_length, half_length)):
        for i in range(segments + 1):
            a = 2 * np.pi * i / segments
            vertices.append((radius * np.cos(a), radius * np.sin(a), z))
            uv.append((i / segments, float(j)))
    n = segments + 1
    for i in range(segments):
        a, b, c, d = i, i + 1, n + i, n + i + 1
        faces += [(a, b, d), (a, d, c)]
    return np.asarray(vertices), np.asarray(faces), np.asarray(uv)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", required=True, help="T07 presentation-r2 studio-v2 export folder")
    args = parser.parse_args()
    source = Path(args.source)
    out = HERE / "assets"
    out.mkdir(exist_ok=True)
    geometry = np.load(source / "geometry.npz")
    for index, name in MESHES.items():
        write_obj(out / f"{name}.obj", geometry[f"mesh_{index}_vertices"], geometry[f"mesh_{index}_faces"])
    v, f, uv = cell_mesh()
    write_obj(out / "aa_cell.obj", v, f, uv)
    for texture in ("new-aa-wrap.png", "old-aa-wrap.png"):
        shutil.copyfile(source / texture, out / texture.replace("-", "_"))
    files = sorted(p for p in out.iterdir() if p.name != "manifest.json")
    manifest = {
        "source": "T07 'Remote battery replacement' approved presentation export (presentation-r2/studio-v2): "
        "meshes 0-3 of geometry.npz and the AA wrap textures; aa_cell.obj generated (original).",
        "source_sha256": {
            "geometry.npz": hashlib.sha256((source / "geometry.npz").read_bytes()).hexdigest(),
            "new-aa-wrap.png": hashlib.sha256((source / "new-aa-wrap.png").read_bytes()).hexdigest(),
            "old-aa-wrap.png": hashlib.sha256((source / "old-aa-wrap.png").read_bytes()).hexdigest(),
        },
        "files": {p.name: {"sha256": hashlib.sha256(p.read_bytes()).hexdigest(), "bytes": p.stat().st_size} for p in files},
    }
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
