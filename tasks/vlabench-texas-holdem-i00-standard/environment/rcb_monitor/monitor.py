#!/usr/bin/env python3
"""rcb_monitor: the trusted resource-limits monitor sidecar of every task (docs/PROTOCOL.md §2.10, record rcb-monitor/1).

Runs as the compose service `rcb_monitor` (generated by scripts/rcb_monitor/inject.py): `pid: host`, `cgroup: host`,
`network_mode: none`, CAP_SYS_PTRACE, the task's GPU reservation, its code read-only from the task directory. The agent
cannot see it (another PID namespace), reach it (no network) or write its record (its own file system).

Which containers it watches: the services that mount the trial's beacon volume `rcb_limits` (read-only at
/run/rcb-limits) are in scope, the ones that mount `rcb_observe` are only recorded (standard modes: the simulator
sidecar). The compose project names both volumes, so they are unique to the trial; the monitor finds the containers as
the mount namespaces whose /run/rcb-limits is the same directory as its own (docker compose exec'd processes included).

Every tick (5 s; disk every 60 s) it samples, per container and summed over the scope: GPU memory (NVML, per process,
compute and graphics), memory (cgroup anon+shmem when the container has its own cgroup, else PSS anon+shmem), processes
(TGIDs), disk growth under the limits' disk_paths in the agent's container, OOM kills, CPU (recorded only). It appends
to /var/rcb-monitor/samples.jsonl and events.jsonl and writes the agent-visible /run/rcb-limits/usage.json.

RCB_LIMITS_ENFORCE=1 (run-time switch; compose default 0): once a violation is confirmed (rcb_limits.violations, the
verifier's own rule) the monitor SIGKILLs every in-scope process except each container's PID 1, so the agent stops at
once and Harbor goes on to collection and the verifier (an agent killed this way ends like one that exited non-zero).
0: it only records.

    python3 monitor.py run            # the service's command
    python3 monitor.py seal --wait 90 # the first sidecar collect hook: seal the record (summary.json), print it
"""
import ctypes
import json
import os
import signal
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import rcb_limits  # noqa: E402
import selftest  # noqa: E402

REC = os.environ.get("RCB_MONITOR_RECORD", "/var/rcb-monitor")
SCOPE_BEACON, OBSERVE_BEACON = "/run/rcb-limits", "/run/rcb-observe"
LIMITS = os.path.join(HERE, "limits.json")
HZ = os.sysconf("SC_CLK_TCK")
PAGE = os.sysconf("SC_PAGE_SIZE")
GIB = float(2 ** 30)


# --------------------------------------------------------------------------------------------------- small helpers
def now():
    return time.time()


def rl(p):
    try:
        return os.readlink(p)
    except OSError:
        return None


def read(p):
    try:
        with open(p) as f:
            return f.read()
    except OSError:
        return None


def stat_id(p):
    try:
        st = os.stat(p)
        return (st.st_dev, st.st_ino)
    except OSError:
        return None


def proc_stat(pid):
    """(starttime, utime+stime) or None."""
    s = read(f"/proc/{pid}/stat")
    if not s:
        return None
    try:
        f = s.rsplit(")", 1)[1].split()
        return int(f[19]), int(f[11]) + int(f[12])
    except (IndexError, ValueError):
        return None


def status(pid):
    s = read(f"/proc/{pid}/status")
    if not s:
        return {}
    d = {}
    for line in s.splitlines():
        k, _, v = line.partition(":")
        d[k] = v.strip()
    return d


def kb(v):
    try:
        return int((v or "0").split()[0])
    except (ValueError, IndexError):
        return 0


def append(name, obj):
    with open(os.path.join(REC, name), "a") as f:
        f.write(json.dumps(obj, separators=(",", ":")) + "\n")


def write_json(path, obj):
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        json.dump(obj, f, indent=1)
    os.replace(tmp, path)


def event(kind, **kw):
    kw.update(t=round(now(), 2), event=kind)
    append("events.jsonl", kw)


def no_dump():
    """Not dumpable: without CAP_SYS_PTRACE nobody (not even the same uid) can open /proc/<monitor>/{root,mem,fd}."""
    try:
        ctypes.CDLL(None, use_errno=True).prctl(4, 0, 0, 0, 0)    # PR_SET_DUMPABLE = 4
    except Exception:
        pass


# --------------------------------------------------------------------------------------------------- NVML
class Nvml:
    """Per-process GPU memory (host PIDs: the monitor runs in the host PID namespace) and per-card use, via libnvidia-ml
    (ctypes; no nvidia-smi child processes)."""

    class Proc(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong),
                    ("gpuInstanceId", ctypes.c_uint), ("computeInstanceId", ctypes.c_uint)]

    class Proc1(ctypes.Structure):
        _fields_ = [("pid", ctypes.c_uint), ("usedGpuMemory", ctypes.c_ulonglong)]

    class Mem(ctypes.Structure):
        _fields_ = [("total", ctypes.c_ulonglong), ("free", ctypes.c_ulonglong), ("used", ctypes.c_ulonglong)]

    def __init__(self):
        self.lib = ctypes.CDLL("libnvidia-ml.so.1")
        if self.lib.nvmlInit_v2() != 0:
            raise RuntimeError("nvmlInit failed")
        n = ctypes.c_uint(0)
        self.lib.nvmlDeviceGetCount_v2(ctypes.byref(n))
        self.handles = []
        for i in range(n.value):
            h = ctypes.c_void_p()
            if self.lib.nvmlDeviceGetHandleByIndex_v2(i, ctypes.byref(h)) == 0:
                self.handles.append(h)
        self.fns = []
        for name, st in (("nvmlDeviceGetComputeRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v3", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetGraphicsRunningProcesses_v2", self.Proc),
                         ("nvmlDeviceGetComputeRunningProcesses", self.Proc1),
                         ("nvmlDeviceGetGraphicsRunningProcesses", self.Proc1)):
            kind = "compute" if "Compute" in name else "graphics"
            if any(k == kind for k, _, _ in self.fns):
                continue
            try:
                self.fns.append((kind, getattr(self.lib, name), st))
            except AttributeError:
                pass

    def sample(self):
        """({host pid: MiB}, {card index: (used MiB, total MiB)})."""
        per, cards = {}, {}
        for i, h in enumerate(self.handles):
            m = self.Mem()
            if self.lib.nvmlDeviceGetMemoryInfo(h, ctypes.byref(m)) == 0:
                cards[i] = (m.used // 2 ** 20, m.total // 2 ** 20)
            seen = {}
            for _kind, fn, st in self.fns:
                cnt = ctypes.c_uint(0)
                rc = fn(h, ctypes.byref(cnt), None)
                if rc not in (0, 7):                 # 7 = NVML_ERROR_INSUFFICIENT_SIZE: cnt now holds the count
                    continue
                cnt = ctypes.c_uint(cnt.value + 16)
                arr = (st * cnt.value)()
                if fn(h, ctypes.byref(cnt), arr) != 0:
                    continue
                for k in range(cnt.value):
                    mem = arr[k].usedGpuMemory
                    mib = 0 if mem >= 2 ** 63 else mem // 2 ** 20     # NVML_VALUE_NOT_AVAILABLE
                    seen[arr[k].pid] = max(seen.get(arr[k].pid, 0), mib)   # a C+G process is in both lists
            for p, v in seen.items():
                per[p] = per.get(p, 0) + v
        return per, cards


# --------------------------------------------------------------------------------------------------- the monitor
class Monitor:
    def __init__(self):
        self.lim = rcb_limits.read_json(LIMITS) or {}
        self.tick = float(self.lim.get("tick_sec", 5))
        self.disk_tick = float(self.lim.get("disk_tick_sec", 60))
        self.enforce = int(bool(int(os.environ.get("RCB_LIMITS_ENFORCE", "0") or 0)))
        self.me_mnt = rl("/proc/self/ns/mnt")
        self.beacon = {"scope": stat_id(SCOPE_BEACON), "observe": stat_id(OBSERVE_BEACON)}
        self.cls = {}            # mnt ns -> ("scope"|"observe"|None, role, first seen)
        self.prev_cpu = {}       # pid -> (starttime, ticks, t)
        self.oom = {}            # cgroup path -> oom_kill count
        self.disk_base = None
        self.disk_last = 0.0
        self.disk_gb = None
        self.series = []         # [(t, {metric: value})] of the last window, for enforcement decisions
        self.confirmed = {}      # metric -> time
        self.kill_until = 0.0
        self.killed = 0
        self.scope_seen = False
        self.caps = selftest.capabilities()
        self.nvml = None
        try:
            self.nvml = Nvml()
        except Exception as e:
            self.caps["nvml_error"] = f"{type(e).__name__}: {e}"[:200]
        self.caps["nvml"] = int(self.nvml is not None)
        self.caps["nvml_devices"] = len(self.nvml.handles) if self.nvml else 0
        self.t0 = now()

    # ---- scope discovery
    def classify(self, mnt, pid):
        c = self.cls.get(mnt)
        if c is not None:
            return c
        root = f"/proc/{pid}/root"
        kind = None
        if self.beacon["scope"] and stat_id(root + SCOPE_BEACON) == self.beacon["scope"]:
            kind = "scope"
        elif self.beacon["observe"] and stat_id(root + OBSERVE_BEACON) == self.beacon["observe"]:
            kind = "observe"
        role = None
        if kind:
            role = "main" if os.path.isdir(root + "/logs/agent") else "sidecar"
        c = (kind, role, now())
        if kind or rl(f"/proc/{pid}/ns/mnt") == mnt:           # a vanished pid tells nothing: ask again next time
            self.cls[mnt] = c
        return c

    def groups(self):
        """{mnt ns: {"kind", "role", "pids": [...]}} of the watched containers."""
        out = {}
        for d in os.listdir("/proc"):
            if not d.isdigit():
                continue
            pid = int(d)
            mnt = rl(f"/proc/{pid}/ns/mnt")
            if mnt is None or mnt == self.me_mnt:
                continue
            kind, role, _ = self.classify(mnt, pid)
            if not kind:
                continue
            g = out.setdefault(mnt, {"kind": kind, "role": role, "pids": []})
            g["pids"].append(pid)
        return out

    # ---- per-container measurements
    def cgroup_of(self, pids):
        """The container's own cgroup v2 directory (under the host tree, `cgroup: host`) when every process in it is this
        container's (rootless podman without cgroup delegation leaves containers in a shared one), else None."""
        paths = set()
        for p in pids[:8]:
            s = read(f"/proc/{p}/cgroup") or ""
            for line in s.splitlines():
                if line.startswith("0::"):
                    paths.add(line[3:].strip())
        if len(paths) != 1:
            return None
        d = "/sys/fs/cgroup" + paths.pop()
        procs = read(d + "/cgroup.procs")
        if procs is None:
            return None
        members = {int(x) for x in procs.split() if x.isdigit()}
        return d if members and members <= set(pids) else None

    def mem_pss(self, pids):
        tot = 0
        for p in pids:
            s = read(f"/proc/{p}/smaps_rollup")
            if s is None:
                st = status(p)
                tot += kb(st.get("RssAnon")) + kb(st.get("RssShmem"))
                continue
            d = {}
            for line in s.splitlines():
                k, _, v = line.partition(":")
                d[k] = v
            tot += (kb(d.get("Pss_Anon")) + kb(d.get("Pss_Shmem"))) if "Pss_Anon" in d else kb(d.get("Pss"))
        return tot / 1024.0 / 1024.0          # GiB

    def measure(self, g, gpu_per, t):
        pids = g["pids"]
        threads = cpu = 0.0
        for p in pids:
            threads += int(status(p).get("Threads", "0") or 0)
            ps = proc_stat(p)
            if ps:
                pv = self.prev_cpu.get(p)
                if pv and pv[0] == ps[0] and t > pv[2]:
                    cpu += max(0, ps[1] - pv[1]) / HZ / (t - pv[2])
                self.prev_cpu[p] = (ps[0], ps[1], t)
        cg = self.cgroup_of(pids)
        m = {"kind": g["kind"], "role": g["role"], "processes": len(pids), "threads": int(threads), "cpu": round(cpu, 2),
             "gpu_memory_gb": round(sum(gpu_per.get(p, 0) for p in pids) / 1024.0, 3), "cgroup": int(cg is not None)}
        if cg:
            st = {}
            for line in (read(cg + "/memory.stat") or "").splitlines():
                k, _, v = line.partition(" ")
                st[k] = v
            try:
                m["memory_gb"] = round((int(st.get("anon", 0)) + int(st.get("shmem", 0))) / GIB, 3)
            except ValueError:
                m["memory_gb"] = round(self.mem_pss(pids), 3)
            mx = (read(cg + "/memory.max") or "").strip()
            m["memory_cap_gb"] = None if mx in ("", "max") else round(int(mx) / GIB, 2)
            for line in (read(cg + "/memory.events") or "").splitlines():
                if line.startswith("oom_kill "):
                    n = int(line.split()[1])
                    old = self.oom.get(cg)
                    if old is not None and n > old:
                        event("oom", role=g["role"], scope=g["kind"] == "scope", count=n - old)
                    self.oom[cg] = n
        else:
            m["memory_gb"] = round(self.mem_pss(pids), 3)
        return m

    def disk(self, main_pid):
        """GiB under disk_paths in the agent's container (st_blocks, (dev, ino) once, no crossing into other mounts,
        disk_exclude skipped, at most 10 s), or None."""
        root = f"/proc/{main_pid}/root"
        paths = self.lim.get("disk_paths") or ["/app"]
        excl = [root + x.rstrip("/") for x in (self.lim.get("disk_exclude") or [])]
        seen, tot, t_end, partial = set(), 0, now() + 10, False
        for base in paths:
            top = root + base
            try:
                dev = os.lstat(top).st_dev
            except OSError:
                continue
            for d, dirs, files in os.walk(top):
                if now() > t_end:
                    partial = True
                    break
                dirs[:] = [x for x in dirs if os.path.join(d, x) not in excl]
                for fn in files + dirs:
                    try:
                        st = os.lstat(os.path.join(d, fn))
                    except OSError:
                        continue
                    if st.st_dev != dev:
                        if fn in dirs:
                            dirs.remove(fn)
                        continue
                    k = (st.st_dev, st.st_ino)
                    if k in seen:
                        continue
                    seen.add(k)
                    tot += st.st_blocks * 512
        if partial:
            event("disk_partial", gb=round(tot / GIB, 3))
        return tot / GIB

    # ---- enforcement
    @staticmethod
    def spared(pids):
        """The container's own processes that must outlive a kill: its PID 1 and what PID 1 started with it (Harbor's
        `sh -c "sleep infinity"` keepalive). Agent processes are exec'd into the container (their parent is outside
        it) or, when orphaned, adopted by PID 1 later: those are never spared."""
        st = {p: status(p) for p in pids}
        init = [p for p in pids if (st[p].get("NSpid") or "").split()[-1:] == ["1"]]
        if not init:
            return set()
        t1 = (proc_stat(init[0]) or (0, 0))[0]
        keep = set(init)
        for p in pids:
            ns_ppid = None
            ns = (st[p].get("NSpid") or "").split()
            if ns and st[p].get("PPid") is not None:
                # PPid in /proc/<pid>/status is in the reader's namespace (host); compare with PID 1's host PID
                ns_ppid = int(st[p]["PPid"])
            ps = proc_stat(p)
            if ns_ppid == init[0] and ps and ps[0] - t1 <= 2 * HZ:   # started with the container, not adopted later
                keep.add(p)
        return keep

    def kill_scope(self, groups, why):
        n = 0
        for mnt, g in groups.items():
            if g["kind"] != "scope":
                continue
            snap = {p: proc_stat(p) for p in g["pids"]}
            keep = self.spared(g["pids"])
            for p in g["pids"]:
                if p in keep:
                    continue                          # PID 1 and its keepalive: the container stays up for collection
                if rl(f"/proc/{p}/ns/mnt") != mnt or not snap[p] or proc_stat(p) is None \
                        or proc_stat(p)[0] != snap[p][0]:
                    continue                          # gone, or its PID now names another process
                try:
                    os.kill(p, signal.SIGKILL)
                    n += 1
                except OSError:
                    pass
        if n:
            self.killed += n
            event("kill", why=why, processes=n)
        return n

    def check(self, t, scope_vals, groups, cards):
        self.series.append((t, scope_vals))
        window = float(self.lim.get("window_sec", 2 * float(self.lim.get("sustain_sec", 60))))
        self.series = [x for x in self.series if x[0] >= t - window - 3 * self.tick]
        samples = [{"t": a, "scope": b} for a, b in self.series]
        for v in rcb_limits.violations(samples, self.lim):
            if v["metric"] not in self.confirmed:
                self.confirmed[v["metric"]] = t
                event("violation", **v)
                if self.enforce:
                    self.kill_until = t + 60
        if self.enforce and t <= self.kill_until:
            self.kill_scope(groups, ",".join(sorted(self.confirmed)))
        # emergency (enforced runs only): protect the machine's other trials when no cgroup cap holds the memory, or
        # the card is about to run out
        if self.enforce:
            cap = (self.lim.get("caps") or {}).get("main", {}).get("memory_gb")
            lim_gpu = float(self.lim.get("max_gpu_memory_gb") or 0)
            full = any(u / float(tt) > 0.97 for u, tt in cards.values() if tt) if cards else False
            if cap and scope_vals["memory_gb"] > float(cap) and not any(
                    m.get("memory_cap_gb") for m in self._last_measures if m["kind"] == "scope"):
                self._emergency(groups, "memory", cap, scope_vals["memory_gb"], key="mem")
            if lim_gpu and (scope_vals["gpu_memory_gb"] > 1.5 * lim_gpu or (full and scope_vals["gpu_memory_gb"] > lim_gpu)):
                self._emergency(groups, "gpu_memory", lim_gpu, scope_vals["gpu_memory_gb"], key="gpu")

    def _emergency(self, groups, why, limit, observed, key):
        best, bv = None, -1
        for g in groups.values():
            if g["kind"] != "scope":
                continue
            keep = self.spared(g["pids"])
            for p in g["pids"]:
                if p in keep:
                    continue
                v = self._gpu_per.get(p, 0) if key == "gpu" else kb(status(p).get("VmRSS"))
                if v > bv:
                    best, bv = p, v
        if best:
            try:
                os.kill(best, signal.SIGKILL)
                self.killed += 1
                event("emergency_kill", why=why, limit=limit, observed=round(observed, 3), processes=1)
            except OSError:
                pass

    # ---- main loop
    def run(self):
        os.makedirs(REC, exist_ok=True)
        restarted = os.path.exists(os.path.join(REC, "meta.json"))
        meta = {"format": rcb_limits.FORMAT, "started": round(self.t0, 2), "enforce": self.enforce, "limits": self.lim,
                "capabilities": self.caps, "beacons": {k: bool(v) for k, v in self.beacon.items()}}
        if restarted:
            event("restart", capabilities=self.caps)
        else:
            write_json(os.path.join(REC, "meta.json"), meta)
            event("start", enforce=self.enforce, capabilities=self.caps)
        if not self.beacon["scope"]:
            event("fatal", why="no scope beacon mounted at /run/rcb-limits")
        if self.lim.get("gpu") and not self.nvml:
            event("fatal", why="GPU task but NVML is unavailable: " + str(self.caps.get("nvml_error")))
        self._last_measures, self._gpu_per = [], {}
        self.fatal_scope = False
        while not os.path.exists(os.path.join(REC, "seal.request")):
            t = now()
            try:
                self.tick_once(t)
            except Exception as e:                    # a vanished process mid-read must never stop the record
                import traceback
                traceback.print_exc()
                event("error", why=f"{type(e).__name__}: {e}"[:300])
            for p in list(self.prev_cpu):
                if t - self.prev_cpu[p][2] > 60:
                    del self.prev_cpu[p]
            time.sleep(max(0.2, self.tick - (now() - t)))
        self.seal()
        while True:                                   # stay up: Harbor copies the record after the hook
            time.sleep(3600)

    def tick_once(self, t):
        groups = self.groups()
        gpu_per, cards = self.nvml.sample() if self.nvml else ({}, {})
        self._gpu_per = gpu_per
        ms = [self.measure(g, gpu_per, t) for g in groups.values()]
        self._last_measures = ms
        scope = [m for m in ms if m["kind"] == "scope"]
        if scope and not self.scope_seen:
            self.scope_seen = True
            event("scope_found", containers=len(scope), roles=sorted(m["role"] for m in scope))
        if not self.scope_seen and not self.fatal_scope and t - self.t0 > 120:
            self.fatal_scope = True
            event("fatal", why="no container mounting the trial's beacon found within 120 s")
        mains = [g for g in groups.values() if g["kind"] == "scope" and g["role"] == "main"]
        if mains and t - self.disk_last >= self.disk_tick:
            d = self.disk(min(mains[0]["pids"]))
            self.disk_last = t
            if d is not None:
                if self.disk_base is None:
                    self.disk_base = d
                self.disk_gb = round(max(0.0, d - self.disk_base), 3)
            disk_now = self.disk_gb
        else:
            disk_now = None
        vals = {"gpu_memory_gb": round(sum(m["gpu_memory_gb"] for m in scope), 3),
                "memory_gb": round(sum(m["memory_gb"] for m in scope), 3),
                "processes": sum(m["processes"] for m in scope), "disk_gb": disk_now}
        obs = [m for m in ms if m["kind"] == "observe"]
        append("samples.jsonl", {"t": round(t, 2), "scope": vals,
                                 "observe": {"gpu_memory_gb": round(sum(m["gpu_memory_gb"] for m in obs), 3),
                                             "memory_gb": round(sum(m["memory_gb"] for m in obs), 3),
                                             "processes": sum(m["processes"] for m in obs)},
                                 "cards": {str(k): v for k, v in cards.items()}, "containers": ms})
        self.check(t, vals, groups, cards)
        try:
            write_json(SCOPE_BEACON + "/usage.json", {
                "t": round(t, 2), "gpu_memory_gb": vals["gpu_memory_gb"], "memory_gb": vals["memory_gb"],
                "processes": vals["processes"], "disk_gb": self.disk_gb, "enforced": self.enforce,
                "limits": {k: self.lim.get(k) for k in ("max_gpu_memory_gb", "max_memory_gb", "max_processes",
                                                        "max_disk_gb", "sustain_sec", "window_sec")},
                "violations": sorted(self.confirmed)})
        except OSError:
            pass

    def seal(self):
        summary, samples, events = rcb_limits.load_record(REC)
        viol = rcb_limits.violations(samples, self.lim, events)
        meta = rcb_limits.read_json(os.path.join(REC, "meta.json")) or {}
        write_json(os.path.join(REC, "summary.json"), {
            "format": rcb_limits.FORMAT, "sealed": True, "enforce": meta.get("enforce", self.enforce),
            "started": meta.get("started"), "ended": round(now(), 2), "n_samples": len(samples),
            "scope_seen": self.scope_seen or any((s.get("scope") or {}).get("processes") for s in samples),
            "peaks": rcb_limits.peaks(samples), "violations": viol, "killed": self.killed,
            "restarts": sum(1 for e in events if e.get("event") == "restart"),
            "capabilities": meta.get("capabilities", self.caps), "limits": self.lim})
        event("seal", violations=len(viol))


def seal_cmd(wait):
    open(os.path.join(REC, "seal.request"), "a").close()
    path = os.path.join(REC, "summary.json")
    t_end = now() + wait
    while now() < t_end and not os.path.exists(path):
        time.sleep(0.5)
    s = rcb_limits.read_json(path)
