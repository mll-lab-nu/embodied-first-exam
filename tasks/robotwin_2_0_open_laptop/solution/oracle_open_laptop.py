# Reference solution for robotwin_2_0_open_laptop: RoboTwin 2.0's expert methods from envs/open_laptop.py upstream
# (play_once), copied verbatim and bound onto the task env. These methods are scrubbed from the agent image.
# Runs with `env` (RoboTwin task env) in scope (rcb_traj.Session.exec_code).
import types
import numpy as np
import sapien
from envs.utils import *
from envs._GLOBAL_CONFIGS import *


def play_once(self):
        face_prod = get_face_prod(self.laptop.get_pose().q, [1, 0, 0], [1, 0, 0])
        arm_tag = ArmTag("left" if face_prod > 0 else "right")
        self.arm_tag = arm_tag

        # Grasp the laptop
        self.move(self.grasp_actor(self.laptop, arm_tag=arm_tag, pre_grasp_dis=0.08, contact_point_id=0))

        for _ in range(15):
            # Get target rotation pose
            self.move(
                self.grasp_actor(
                    self.laptop,
                    arm_tag=arm_tag,
                    pre_grasp_dis=0.0,
                    grasp_dis=0.0,
                    contact_point_id=1,
                ))
            if not self.plan_success:
                break
            if self.check_success(target=0.5):
                break

        self.info["info"] = {
            "{A}": f"{self.model_name}/base{self.model_id}",
            "{a}": str(arm_tag),
        }
        return self.info


for _f in (play_once,):
    setattr(env, _f.__name__, types.MethodType(_f, env))
env.play_once()
assert env.plan_success, "a planning step failed"
