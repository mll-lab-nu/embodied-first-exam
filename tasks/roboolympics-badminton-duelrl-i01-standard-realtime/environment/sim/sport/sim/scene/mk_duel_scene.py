#!/usr/bin/env python3
"""Write the two-robot badminton scene of the duel's renderer (bm_duel.xml, next to this file) from the match scene.

The duel's physics runs each robot in its own copy of the single-player model (scene/bm_scene.xml; see
duel/environment/sim/bduel.py); this scene only DRAWS both: robot A as in bm_scene.xml, robot B as a copy of the same
robot body (every name suffixed `_b`) inside a body rotated 180 degrees about z, so that B's joint values are those of
B's own frame (x, y, z) -> (-x, -y, z). No actuators are copied (the renderer only sets joint positions).

    python3 sports/badminton/sim/scene/mk_duel_scene.py        (then tools/generate.py badminton)

The header written into bm_duel.xml keeps the wording of the legacy script (scripts/olympiad/badminton/), so the
scene file stays byte-identical to the one the legacy duel recordings were made with.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "bm_scene.xml"
OUT = HERE / "bm_duel.xml"


def robot_block(xml: str) -> str:
    """The <body name="base"> element (the whole robot), found by balancing <body> tags."""
    i = xml.index('<body name="base"')
    depth, j = 0, i
    for m in re.finditer(r"<body\b[^>]*?(/?)>|</body>", xml[i:]):
        if m.group(0).startswith("</"):
            depth -= 1
        elif not m.group(1):
            depth += 1
        if depth == 0:
            j = i + m.end()
            break
    return xml[i:j]


def main():
    xml = SRC.read_text()
    block = robot_block(xml)
    copy = re.sub(r'\bname="([^"]+)"', r'name="\1_b"', block)
    side_b = ('\n    <!-- robot B: the same robot in B\'s frame, (x, y, z) -> (-x, -y, z) -->\n'
              '    <body name="side_b" quat="0 0 0 1">\n    ' + copy + '\n    </body>\n')
    out = xml.replace(block, block + side_b)
    out = out.replace('<mujoco model="rcb_badminton">', '<mujoco model="rcb_badminton_duel">')
    out = re.sub(r"<!--.*?-->", "", out, count=1, flags=re.S)
    header = ("<!--\n  Robot badminton DUEL scene (render only), generated by scripts/olympiad/badminton/mk_duel_scene.py from\n"
              "  bm_scene.xml: robot A as in the match scene; robot B (names *_b, identical) the same robot in\n"
              "  a body rotated 180 degrees about z. The physics runs each robot in its own copy of bm_scene.xml (bduel.py).\n-->\n")
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + out.lstrip())
    print("wrote", OUT)


if __name__ == "__main__":
    main()
