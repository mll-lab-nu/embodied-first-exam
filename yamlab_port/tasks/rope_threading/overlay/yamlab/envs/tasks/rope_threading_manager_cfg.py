"""Configuration for the RopeThreading tasks (port of RoboTangle rope_threading, tiers easy / medium).

Scene = YAMLab's YAM workstation + the rope (one PhysX articulation: 110 capsules r 4 mm, d 10 mm,
spherical joints with implicit PD drives towards the start shape, see rope_threading_lib/rope_params.py)
+ the fixtures (rings, stands, bases as static colliders, rope_threading_lib/fixtures_usd.py).
Assets per tier are generated by tools/build_assets.py into rope_threading_lib/assets/<tier>/.
The rope / fixture structure follows knot_untying's validated rope model (knot_untying_manager_cfg.py).
"""

import json
import os

import torch

import isaaclab.sim as sim_utils
import isaaclab.envs.mdp as mdp
from isaaclab.actuators import ImplicitActuatorCfg
from isaaclab.assets import ArticulationCfg, AssetBaseCfg
from isaaclab.managers import EventTermCfg, RewardTermCfg, SceneEntityCfg, TerminationTermCfg
from isaaclab.utils import configclass

from yamlab.envs.yam_bimanual_scene import YamBimanualSceneCfg

from .yam_bimanual_env_cfg import YamBimanualEnvCfg, BaseEventsCfg
from .rope_threading_lib import rope_params as RP

ASSET_ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "rope_threading_lib", "assets")
TIERS = {"RopeThreading-Easy-v0": "easy", "RopeThreading-Medium-v0": "medium"}


def _link_length(tier):
    meta = os.path.join(ASSET_ROOT, tier, "rope_meta.json")
    if os.path.exists(meta):
        return json.load(open(meta))["link_length_m"]
    return RP.LENGTH / RP.N_LINKS


def rope_cfg(tier: str) -> ArticulationCfg:
    d = _link_length(tier)
    P = RP.ROPE
    return ArticulationCfg(
        prim_path="{ENV_REGEX_NS}/rope",
        spawn=sim_utils.UsdFileCfg(usd_path=os.path.join(ASSET_ROOT, tier, "rope.usda")),
        # Root pose / joint coordinates are overwritten from start_state.npz by the manager.
        init_state=ArticulationCfg.InitialStateCfg(pos=(0.0, 0.0, 0.0)),
        actuators={
            "rope_bend": ImplicitActuatorCfg(joint_names_expr=[r"j_\d+:1", r"j_\d+:2"],
                                             stiffness=RP.bend_stiffness(d), damping=P["joint_damping"],
                                             armature=P["armature"]),
            "rope_twist": ImplicitActuatorCfg(joint_names_expr=[r"j_\d+:0"],
                                              stiffness=RP.twist_stiffness(d), damping=P["joint_damping"],
                                              armature=P["armature"]),
        },
    )


def fixtures_cfg(tier: str) -> AssetBaseCfg:
    return AssetBaseCfg(prim_path="{ENV_REGEX_NS}/fixtures",
                        spawn=sim_utils.UsdFileCfg(usd_path=os.path.join(ASSET_ROOT, tier, "fixtures.usda")))


def reset_rope_joint_targets(env, env_ids, asset_cfg: SceneEntityCfg):
    """reset_scene_to_default sets joint targets = default joint pos (the settled start); the drives must
    pull towards the rest shape (= the authored start U, release profile rope_reference_shape 'initial')."""
    rope = env.scene[asset_cfg.name]
    tgt = getattr(env, "rope_rest_joint_pos", None)
    if tgt is None:
        tgt = torch.zeros(rope.num_joints, device=rope.device)
    rope.set_joint_position_target(tgt.unsqueeze(0).repeat(len(env_ids), 1), env_ids=env_ids)
    rope.set_joint_velocity_target(torch.zeros(len(env_ids), rope.num_joints, device=rope.device), env_ids=env_ids)


def threading_goal_success(env):
    return env.update_goal()


def rope_fell_off_table(env, margin: float = 0.05):
    z = env.scene["rope"].data.body_link_pos_w[..., 2] - env.scene.env_origins[:, 2:3]
    return (z < 0.75 - margin).any(dim=1)


def _scene_cfg(tier: str):
    @configclass
    class _Scene(YamBimanualSceneCfg):
        rope = rope_cfg(tier)
        fixtures = fixtures_cfg(tier)
    _Scene.__name__ = f"RopeThreading{tier.title()}SceneCfg"
    return _Scene


@configclass
class RopeThreadingEventsCfg(BaseEventsCfg):
    reset_rope_targets = EventTermCfg(func=reset_rope_joint_targets, mode="reset",
                                      params={"asset_cfg": SceneEntityCfg("rope")})


def threading_success_reward(env):
    return env.goal_latched.float()


@configclass
class RopeThreadingRewardsCfg:
    success = RewardTermCfg(func=threading_success_reward, params={}, weight=1.0)


@configclass
class RopeThreadingTerminationsCfg:
    time_out = TerminationTermCfg(func=mdp.time_out, time_out=True)
    task_success = TerminationTermCfg(func=threading_goal_success, params={})
    # (no rope-off-table termination: the old task has none, and the oracle hangs the rope end over the table edge)


def _env_cfg(tier: str):
    Scene = _scene_cfg(tier)

    @configclass
    class _Cfg(YamBimanualEnvCfg):
        scene: Scene = Scene(num_envs=1, env_spacing=3.0)
        events: RopeThreadingEventsCfg = RopeThreadingEventsCfg()
        rewards: RopeThreadingRewardsCfg = RopeThreadingRewardsCfg()
        terminations: RopeThreadingTerminationsCfg = RopeThreadingTerminationsCfg()
        obj_name_to_event_name: dict = {}

        def __post_init__(self):
            super().__post_init__()
            # Finger contact sensors (YamRobot requires them) need one filter body per object (PhysX tensor
            # filters must match one body per env): they filter the rope's last link (the end the oracle
            # feeds). is_grasping() and the grasp clamp are therefore NOT meaningful for the rope.
            self._contact_body_links = {"rope": "link_109"}
            # The default recorder file (/tmp/isaaclab/logs/dataset.hdf5) is shared by every process on the host:
            # a second concurrent run fails on its h5 lock. Use a per-process file (export mode is unchanged).
            if getattr(self, "recorders", None) is not None:
                self.recorders.dataset_export_dir_path = f"/tmp/rope_threading_rec/{os.getpid()}"

    _Cfg.__name__ = f"RopeThreading{tier.title()}ManagerEnvCfg"
    _Cfg.TIER = tier
    _Cfg.CONTACT_OBJECT_NAMES = []
    return _Cfg


RopeThreadingEasyManagerEnvCfg = _env_cfg("easy")
RopeThreadingMediumManagerEnvCfg = _env_cfg("medium")
