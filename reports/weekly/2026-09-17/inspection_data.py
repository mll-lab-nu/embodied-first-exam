def gate(status, evidence, gap, refs):
    return dict(status=status, evidence=evidence, gap=gap, references=refs)


def inspection(title, baseline, gates, extract_now, next_step, summary):
    return dict(title=title, baseline=baseline, gates=dict(zip([g['id'] for g in GATES], gates)),
                extract_now=extract_now, next_step=next_step, summary=summary)


